#!/usr/bin/env node
// Renders the live view of every task-flow run into the project's docs folder.
//
// Why this exists. A run chains seven phases in one invocation and can spend an
// hour inside `build`. From the outside that is a wall of tool calls: there is no
// way to tell which phase is running, which task it is on, or whether it banked a
// question. With more than one run in flight, in different sessions, it is worse.
//
// Why it is GENERATED and never written by the agent. The pipeline already has a
// hook (stop.js) whose whole reason for existing is that prose instructions drift.
// A dashboard the agent updates by hand drifts the same way, and a stale dashboard
// is worse than none because it is believed. So nothing here is transcribed: every
// line is derived from state.json and from the plan's own task headings. That is
// also what keeps the promise that this is not a second copy of the plan.
//
// Nothing project-specific is hard-coded. The docs folder, the page language and
// where the runs live all come from the repository's .claude/task-flow.json,
// through config.js.

